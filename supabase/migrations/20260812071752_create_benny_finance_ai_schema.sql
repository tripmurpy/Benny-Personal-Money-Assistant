alter table public.transactions enable row level security;
alter table public.income enable row level security;
alter table public.chat_sessions enable row level security;
alter table public.chat_messages enable row level security;
alter table public.agent_harness enable row level security;
alter table public.user_preferences enable row level security;
alter table public.spending_assessments enable row level security;
alter table public.roast_runs enable row level security;

revoke all on table public.user_profiles, public.transactions, public.income,
    public.chat_sessions, public.chat_messages, public.agent_harness,
    public.user_preferences, public.spending_assessments, public.roast_runs
from anon, authenticated;
grant select, insert, update, delete on table public.user_profiles, public.transactions,
    public.income, public.chat_sessions, public.chat_messages, public.agent_harness,
    public.user_preferences, public.spending_assessments, public.roast_runs
to service_role;
grant usage, select on all sequences in schema public to service_role;
revoke all on function public.set_updated_at() from public, anon, authenticated;
